"""Export a finished run as a STAC Collection with one Item per segment, and validate it against the STAC schemas.
Usage: python to_stac.py <run> [--license CC-BY-NC-SA-4.0] [--source-href https://doi.org/...]  -> <run>/stac/"""
import argparse
import datetime as dt
import json
import os

import pystac

FILE_EXT = "https://stac-extensions.github.io/file/v2.1.0/schema.json"


def multihash_sha256(hex_digest):
    return "1220" + hex_digest          # multihash prefix for sha2-256 (STAC file extension)


def ts(s):
    return dt.datetime.fromisoformat(s).replace(tzinfo=dt.timezone.utc)


def export(run, license_id, source_href):
    idx = json.load(open(os.path.join(run, "sss_index.geojson"), encoding="utf-8"))
    rec = json.load(open(os.path.join(run, "run_record.json"), encoding="utf-8"))
    mos = json.load(open(os.path.join(run, "segment_mosaic_manifest.json"), encoding="utf-8"))
    ing = rec["ingestion"]
    segs = [f for f in idx["features"] if f["properties"]["kind"] == "segment"]
    track = idx["features"][0]["geometry"]["coordinates"]
    lons, lats = [c[0] for c in track], [c[1] for c in track]
    t0, t1 = ts(segs[0]["properties"]["time_start"]), ts(segs[-1]["properties"]["time_end"])
    coll_id = os.path.basename(os.path.normpath(run))
    out = os.path.join(run, "stac")

    coll = pystac.Collection(
        id=coll_id,
        description=f"Segment-indexed side-scan sonar products derived from {ing['source_file']} "
                    f"(ingestion class: {ing['class']}), generated by sss_pipeline {rec['pipeline_version']}.",
        extent=pystac.Extent(pystac.SpatialExtent([[min(lons), min(lats), max(lons), max(lats)]]),
                             pystac.TemporalExtent([[t0, t1]])),
        license=license_id, stac_extensions=[FILE_EXT],
        extra_fields={"sss:ingestion": ing, "sss:channel_pair": rec["parse"]["channel_pair"],
                      "sss:segmentation": rec["config"]["segment"], "sss:pipeline_version": rec["pipeline_version"]})
    coll.add_asset("source", pystac.Asset(href=source_href or ing["source_file"], title=ing["source_file"],
                                          media_type="application/octet-stream", roles=["source"],
                                          extra_fields={"file:size": ing["source_bytes"],
                                                        "file:checksum": multihash_sha256(ing["source_sha256"])}))
    for key, rel, mt, roles in (("pings", "pings.csv", "text/csv", ["data"]),
                                ("dataset-metadata", "metadata/dataset_mgds.xml", "application/xml", ["metadata"]),
                                ("sss-metadata", "metadata/sss_extended.xml", "application/xml", ["metadata"]),
                                ("segment-index", "sss_index.geojson", "application/geo+json", ["metadata"]),
                                ("run-record", "run_record.json", "application/json", ["metadata"])):
        coll.add_asset(key, pystac.Asset(href=f"../{rel}", media_type=mt, roles=roles))
    if source_href:
        coll.add_link(pystac.Link("derived_from", source_href, title="Source data set"))

    by_seg = {}
    for m in mos:
        by_seg.setdefault(m["segment_id"], []).append(m)
    for f in segs:
        p = f["properties"]
        lon = [c[0] for c in f["geometry"]["coordinates"]]; lat = [c[1] for c in f["geometry"]["coordinates"]]
        item = pystac.Item(
            id=p["segment_id"], geometry=f["geometry"], bbox=[min(lon), min(lat), max(lon), max(lat)],
            datetime=None, start_datetime=ts(p["time_start"]), end_datetime=ts(p["time_end"]),
            properties={"sss:ping_start": p["ping_start"], "sss:ping_end": p["ping_end"],
                        "sss:n_pings": p["n_pings"], "sss:length_m": p["length_m"],
                        "sss:source_sha256": p["source_sha256"], "sss:ingestion_class": p["ingestion_class"]})
        item.add_asset("preview", pystac.Asset(href=f"../../{p['products']['preview']}", media_type="image/png",
                                               roles=["overview"]))
        for m in by_seg.get(p["segment_id"], []):
            prm = m["params"]
            extra = {"sss:slant_range_mode": prm["slant_range_mode"], "sss:fusion": prm["fusion"],
                     "sss:pixel_m": prm["pixel_m"], "sss:range_m": prm["range_m"]}
            item.add_asset(m["product"], pystac.Asset(href=f"../../{m['file']}", media_type="image/png",
                                                      roles=["visual"], extra_fields=extra))
            item.add_asset(m["product"] + "-grid", pystac.Asset(href=f"../../{m['grid']}",
                                                                media_type="application/octet-stream",
                                                                roles=["data"], extra_fields=extra))
        item.add_link(pystac.Link("derived_from", "../../pings.csv", media_type="text/csv",
                                  title=f"pings {p['ping_start']}-{p['ping_end']}"))
        coll.add_item(item)

    coll.normalize_hrefs(out)
    coll.make_all_asset_hrefs_relative()
    coll_schemas = coll.validate()                           # JSON-schema validation of the collection
    n = coll.validate_all()                                  # ... and of every item
    coll.save(catalog_type=pystac.CatalogType.SELF_CONTAINED)
    return {"collection": coll_id, "items": len(segs), "validated_items": n, "collection_schemas": coll_schemas,
            "stac_version": pystac.get_stac_version(), "pystac": pystac.__version__}


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("run")
    ap.add_argument("--license", default="CC-BY-NC-SA-4.0")
    ap.add_argument("--source-href")
    a = ap.parse_args()
    r = export(a.run, a.license, a.source_href)
    json.dump(r, open(os.path.join(a.run, "stac_validation.json"), "w"), indent=2)
    print(r)
